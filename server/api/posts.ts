// ⚡ Bolt: Direct JSON import caches data in memory, avoiding inefficient fs.readFile on every request.
import posts from '../data/posts.json'

export default defineEventHandler(async (event) => {
  try {
    return posts
  } catch (error) {
    throw createError({
      statusCode: 500,
      message: 'Failed to load posts'
    })
  }
})
