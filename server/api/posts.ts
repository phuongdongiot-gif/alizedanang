// ⚡ Bolt: Import JSON directly to cache data in memory and avoid fs.readFile on every request
import posts from '../data/posts.json'

export default defineEventHandler(async (event) => {
  try {
    return posts
  } catch (error) {
    throw createError({
      statusCode: 500,
      message: 'Failed to load posts'
    })
  }
})
