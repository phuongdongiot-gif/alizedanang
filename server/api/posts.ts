// ⚡ Bolt Optimization: Use ES module import instead of fs.readFile to cache JSON data in memory
import posts from '../data/posts.json'

export default defineEventHandler(async (event) => {
  try {
    return posts
  } catch (error) {
    throw createError({
      statusCode: 500,
      message: 'Failed to load posts'
    })
  }
})
